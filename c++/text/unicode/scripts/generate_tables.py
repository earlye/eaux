#!/usr/bin/env python3
"""Generate eaux/text/unicode/detail/tables.hpp from the Unicode Character Database.

Downloads the UCD files for one pinned Unicode version into a cache directory
(never into the source tree), packs the properties the package needs into one
byte per code point, and writes a two-stage lookup table. It also refreshes the
checked-in copy of GraphemeBreakTest.txt that the tests read.

    python3 scripts/generate_tables.py [--version 18.0.0] [--cache DIR]
"""

import argparse
import pathlib
import re
import shutil
import tempfile
import urllib.request

PACKAGE = pathlib.Path(__file__).resolve().parent.parent
HEADER = PACKAGE / "include/eaux/text/unicode/detail/tables.hpp"
TEST_DATA = PACKAGE / "tests/data/GraphemeBreakTest.txt"

FILES = {
    "GraphemeBreakProperty.txt": "auxiliary/GraphemeBreakProperty.txt",
    "GraphemeBreakTest.txt": "auxiliary/GraphemeBreakTest.txt",
    "emoji-data.txt": "emoji/emoji-data.txt",
    "DerivedCoreProperties.txt": "DerivedCoreProperties.txt",
    "EastAsianWidth.txt": "EastAsianWidth.txt",
}

# Order must match enum class grapheme_break in unicode.hpp.
GCB = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator",
       "Prepend", "SpacingMark", "L", "V", "T", "LV", "LVT"]
INCB = ["None", "Linker", "Consonant", "Extend"]

# [format.string.std]: beyond East_Asian_Width W and F, these ranges are wide.
STD_EXTRA_WIDE = [(0x4DC0, 0x4DFF), (0x1F300, 0x1F5FF), (0x1F900, 0x1F9FF)]

MAX = 0x110000
LINE = re.compile(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([^#;]+?)\s*(?:;\s*([^#]+?)\s*)?(?:#.*)?$")


def fetch(version, cache):
    cache.mkdir(parents=True, exist_ok=True)
    base = f"https://www.unicode.org/Public/{version}/ucd/"
    for name, path in FILES.items():
        target = cache / name
        if not target.exists():
            with urllib.request.urlopen(base + path) as response:
                target.write_bytes(response.read())
    header = (cache / "GraphemeBreakTest.txt").read_text(encoding="utf-8").splitlines()[0]
    if version not in header:
        raise SystemExit(f"cache {cache} holds {header!r}, not version {version}")


def records(path):
    for raw in path.read_text(encoding="utf-8").splitlines():
        if raw.startswith("#") or not raw.strip():
            continue
        m = LINE.match(raw)
        if not m:
            raise SystemExit(f"{path.name}: cannot parse {raw!r}")
        first = int(m.group(1), 16)
        last = int(m.group(2), 16) if m.group(2) else first
        yield first, last, m.group(3), m.group(4)


def build(cache):
    gcb = [0] * MAX
    for first, last, value, _ in records(cache / "GraphemeBreakProperty.txt"):
        for cp in range(first, last + 1):
            gcb[cp] = GCB.index(value)

    pictographic = [False] * MAX
    for first, last, value, _ in records(cache / "emoji-data.txt"):
        if value == "Extended_Pictographic":
            for cp in range(first, last + 1):
                pictographic[cp] = True

    incb = [0] * MAX
    for first, last, value, sub in records(cache / "DerivedCoreProperties.txt"):
        if value == "InCB":
            for cp in range(first, last + 1):
                incb[cp] = INCB.index(sub)

    wide = [False] * MAX
    for first, last, value, _ in records(cache / "EastAsianWidth.txt"):
        if value in ("W", "F"):
            for cp in range(first, last + 1):
                wide[cp] = True
    for first, last in STD_EXTRA_WIDE:
        for cp in range(first, last + 1):
            wide[cp] = True

    return [gcb[cp] | pictographic[cp] << 4 | incb[cp] << 5 | wide[cp] << 7 for cp in range(MAX)]


def two_stage(props, shift):
    size = 1 << shift
    blocks, index = {}, []
    for start in range(0, MAX, size):
        block = tuple(props[start:start + size])
        index.append(blocks.setdefault(block, len(blocks)))
    return size, index, list(blocks)


def rows(values, per_line):
    for i in range(0, len(values), per_line):
        yield "    " + ", ".join(str(v) for v in values[i:i + per_line]) + ","


def emit(version, props):
    shift, (size, index, blocks) = min(
        ((s, two_stage(props, s)) for s in range(5, 10)),
        key=lambda c: len(c[1][1]) * (1 if len(c[1][2]) <= 256 else 2) + len(c[1][2]) * c[1][0])
    index_type = "std::uint8_t" if len(blocks) <= 256 else "std::uint16_t"
    data = [v for block in blocks for v in block]
    lines = [
        "// Generated by scripts/generate_tables.py from the Unicode Character Database. Do not edit.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "#include <string_view>",
        "",
        "namespace eaux::text::unicode::detail {",
        "",
        f'inline constexpr std::string_view unicode_version = "{version}";',
        "",
        "// One byte per code point: Grapheme_Cluster_Break in bits 0-3, Extended_Pictographic in",
        "// bit 4, Indic_Conjunct_Break in bits 5-6, and bit 7 set when [format.string.std] gives the",
        "// code point a width of 2.",
        f"inline constexpr unsigned property_shift = {shift};",
        "",
        f"inline constexpr {index_type} property_index[{len(index)}] = {{",
        *rows(index, 32),
        "};",
        "",
        f"inline constexpr std::uint8_t property_blocks[{len(data)}] = {{",
        *rows(data, 32),
        "};",
        "",
        "}  // namespace eaux::text::unicode::detail",
        "",
    ]
    HEADER.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text("\n".join(lines), encoding="utf-8")
    print(f"{HEADER.relative_to(PACKAGE)}: Unicode {version}, shift {shift}, "
          f"{len(index)} index entries, {len(blocks)} blocks of {size}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--version", default="18.0.0", help="Unicode version to pin (default: %(default)s)")
    parser.add_argument("--cache", type=pathlib.Path, help="download directory (default: a temporary directory)")
    args = parser.parse_args()

    with tempfile.TemporaryDirectory() as scratch:
        cache = args.cache or pathlib.Path(scratch)
        fetch(args.version, cache)
        emit(args.version, build(cache))
        TEST_DATA.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(cache / "GraphemeBreakTest.txt", TEST_DATA)


if __name__ == "__main__":
    main()
